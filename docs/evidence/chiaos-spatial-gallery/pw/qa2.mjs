import { chromium } from 'playwright';
const browser = await chromium.launch();
const out = {};
const runs = [['desktop',1440,900,false,false],['tablet',834,1112,false,false],['mobile',390,844,false,false],['reduced',1440,900,false,true],['nowebgl',1440,900,true,false],['nowebgl-mobile',390,844,true,false]];
for (const [name,w,h,guard,reduce] of runs) {
  const ctx = await browser.newContext({ viewport:{width:w,height:h}, reducedMotion: reduce?'reduce':'no-preference' });
  if (guard) await ctx.addInitScript(() => { const g = HTMLCanvasElement.prototype.getContext; HTMLCanvasElement.prototype.getContext = function(t,...a){ if(/webgl/.test(String(t))) return null; return g.call(this,t,...a); }; });
  const page = await ctx.newPage(); const errors = [];
  page.on('console', m => { if (m.type()==='error') errors.push(m.text().slice(0,140)); });
  page.on('pageerror', e => errors.push(String(e).slice(0,160)));
  await page.goto('http://localhost:3217/system', { waitUntil:'networkidle' });
  const before = await page.locator('canvas').count();
  await page.locator('[role=tablist]').evaluate(e => window.scrollTo(0, e.getBoundingClientRect().top + scrollY - 70));
  await page.waitForTimeout(1500);
  const r = { canvasesBefore: before, canvasesAtGallery: await page.locator('canvas').count() };
  await page.locator('#gallery-tab-earth-fm').focus();
  await page.keyboard.press('End');
  r.endKey = await page.locator('[role=tab][aria-selected=true]').textContent();
  await page.keyboard.press('Home');
  r.homeKey = await page.locator('[role=tab][aria-selected=true]').textContent();
  const slider = page.locator('input[type=range]');
  await slider.focus(); await page.keyboard.press('Home');
  r.sliderHome = await page.locator('#gallery-panel [aria-live=polite]').textContent();
  await page.keyboard.press('End');
  r.sliderEnd = await page.locator('#gallery-panel [aria-live=polite]').textContent();
  r.playButton = await page.getByRole('button', { name: /play record/i }).count();
  await page.waitForTimeout(800);
  await page.screenshot({ path:`/tmp/chiaos-qa/gallery/qa-${name}.png` });
  r.fallback = await page.locator('.gallery-fallback').count();
  r.overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth);
  await page.locator('#gallery-tab-fingence').click();
  await page.getByRole('link', { name: 'Read the case study' }).click();
  await page.waitForTimeout(600);
  r.caseStudyHash = await page.evaluate(() => location.hash);
  await page.locator('#contact').evaluate(e => e.scrollIntoView());
  await page.waitForTimeout(1200);
  r.canvasesAfterLeaving = await page.locator('canvas').count();
  r.errors = errors; out[name] = r; await ctx.close();
}
const ctx = await browser.newContext({ viewport:{width:1440,height:900} }); const page = await ctx.newPage();
await page.goto('http://localhost:3217/', { waitUntil:'networkidle' });
out.landing = await page.evaluate(() => ({ h1: document.querySelector('h1')?.textContent?.slice(0,40), overflow: document.documentElement.scrollWidth - innerWidth, icons: [...document.querySelectorAll('link[rel*=icon]')].map(l=>l.getAttribute('href')) }));
await page.screenshot({ path:'/tmp/chiaos-qa/gallery/qa-landing.png' });
await browser.close(); console.log(JSON.stringify(out,null,1));
